%% ------------------------------------------------------------------------
%  amc1306_lpf_design.m
%
%  Design the low-pass filter that follows the AMC1306 sampling chain and
%  emit everything the FPGA build needs:
%
%     ../fir/amc1306_lpf_51tap.coe      Xilinx FIR Compiler coefficient file
%     ../rtl/fir_coefs.vh               same integers, for the RTL reference
%     ../fir/fir_response.csv           magnitude/phase response (for review)
%     ../fir/fir_response.png           plot, if a figure can be exported
%     ../data/fir_spec.vh               |H(f)| at the testbench test points
%
%  Chain context: the AMC1306 module produces one sample every 16 us
%  (16 MHz CLKIN / sinc3 OSR 256)  ->  Fs = 62.5 kSPS.
%
%  Spec: pass band 1 kHz, stop band 2.5 kHz.
%  Order 50 (51 taps) is kept because it was requested -- see the warning
%  printed at the end: at Fs = 62.5 kSPS this transition is only 2.4 % of the
%  sample rate, so 51 taps cannot deliver a "clean" stop band.  The script
%  prints what is actually achieved so the number can go into the report.
% ------------------------------------------------------------------------

clear; clc; close all;

%% ---- knobs -------------------------------------------------------------
Fs      = 62.5e3;      % output rate of the AMC1306 chain
Fpass   = 1.0e3;       % pass-band edge
Fstop   = 2.5e3;       % stop-band edge
Order   = 50;          % filter order -> Order+1 taps (51)
CoefW   = 16;          % coefficient word length (16-bit signed)
StopWt  = 2;           % stop-band weight: 1 = flattest pass band,
                       % higher = more attenuation, more pass-band droop
OutDir  = fullfile(fileparts(mfilename('fullpath')), '..');
FirDir  = fullfile(OutDir, 'fir');
RtlDir  = fullfile(OutDir, 'rtl');
DatDir  = fullfile(OutDir, 'data');
if ~exist(FirDir,'dir'), mkdir(FirDir); end

Taps = Order + 1;

%% ---- design ------------------------------------------------------------
Wn = [0 Fpass Fstop Fs/2] / (Fs/2);
useFirpm = license('test','Signal_Toolbox') && exist('firpm','file') == 2;
if useFirpm
    % the weight trades pass-band ripple against stop-band attenuation
    h = firpm(Order, Wn, [1 1 0 0], [1 StopWt]);
    method = sprintf('firpm (Parks-McClellan, stop-band weight %g)', StopWt);
else
    % fallback: Kaiser window, same order
    [~,Wn_k,beta,ftype] = kaiserord([Fpass Fstop]/(Fs/2), [1 0], [0.01 0.001]);
    h = fir1(Order, Wn_k, ftype, kaiser(Order+1, beta));
    method = sprintf('fir1 + Kaiser (beta=%.2f)', beta);
end
h = h(:).';
fprintf('design method : %s\n', method);

%% ---- quantise to CoefW-bit integers with sum exactly 2^(CoefW-1) --------
hq = round(h / sum(h) * 2^(CoefW-1));
center = (Taps+1)/2;
hq(center) = hq(center) + (2^(CoefW-1) - sum(hq));   % keeps symmetry, fixes DC
hq = max(min(hq, 2^(CoefW-1)-1), -2^(CoefW-1));
assert(sum(hq) == 2^(CoefW-1), 'DC gain normalisation failed');
fprintf('coefficients  : %d taps, %d-bit, sum = %d (= 2^%d)\n', ...
        Taps, CoefW, sum(hq), CoefW-1);

%% ---- response of the *quantised* filter --------------------------------
Nfft = 2^18;
[Hq, f] = freqz(hq/2^(CoefW-1), 1, Nfft, Fs);
magdB  = 20*log10(abs(Hq) + 1e-15);

pb   = magdB(f <= Fpass);
sb   = magdB(f >= Fstop);
ripple   = max(pb) - min(pb);
attn     = -max(sb);
f3       = f(find(magdB <= -3, 1, 'first'));
fprintf('pass band     : ripple %.3f dB  (max %.3f, min %.3f)\n', ...
        ripple, max(pb), min(pb));
fprintf('stop band     : worst-case attenuation %.2f dB at >= %.0f Hz\n', ...
        attn, Fstop);
fprintf('-3 dB point   : %.0f Hz\n', f3);

%% ---- write the Xilinx .coe file ----------------------------------------
coeFile = fullfile(FirDir, sprintf('amc1306_lpf_%dtap.coe', Taps));
fid = fopen(coeFile, 'w');
fprintf(fid, '; Xilinx FIR Compiler coefficient file\n');
fprintf(fid, '; AMC1306 chain LPF: Fs=%.1f Hz, pass=%.0f Hz, stop=%.0f Hz\n', Fs, Fpass, Fstop);
fprintf(fid, '; order %d (%d taps), %d-bit signed, sum = %d (DC gain 1.0)\n', ...
        Order, Taps, CoefW, sum(hq));
fprintf(fid, '; designed by amc1306_lpf_design.m -- %s\n', datestr(now, 'yyyy-mm-dd HH:MM'));
fprintf(fid, 'radix=10;\n');
fprintf(fid, 'coefdata=\n');
for k = 1:Taps
    if k < Taps, sep = ','; else, sep = ';'; end
    fprintf(fid, '  %d%s\n', hq(k), sep);
end
fclose(fid);
fprintf('wrote         : %s\n', coeFile);

%% ---- write the RTL coefficient header (same integers) ------------------
vhFile = fullfile(RtlDir, 'fir_coefs.vh');
fid = fopen(vhFile, 'w');
fprintf(fid, '// AUTO-GENERATED by fir/amc1306_lpf_design.m -- do not edit.\n');
fprintf(fid, '// %d taps, %d-bit signed, sum = %d\n', Taps, CoefW, sum(hq));
fprintf(fid, 'initial begin\n');
for k = 1:Taps
    if hq(k) < 0
        fprintf(fid, '    coef[%2d] = -16''sd%d;\n', k-1, abs(hq(k)));
    else
        fprintf(fid, '    coef[%2d] =  16''sd%d;\n', k-1, hq(k));
    end
end
fprintf(fid, 'end\n');
fclose(fid);
fprintf('wrote         : %s\n', vhFile);

%% ---- test-point gains for the testbench --------------------------------
testHz = [1000 2500 4000 12000];
gains  = zeros(size(testHz));
for k = 1:numel(testHz)
    [~, idx] = min(abs(f - testHz(k)));
    gains(k) = abs(Hq(idx));
end
specFile = fullfile(DatDir, 'fir_spec.vh');
fid = fopen(specFile, 'w');
fprintf(fid, '// AUTO-GENERATED by fir/amc1306_lpf_design.m -- do not edit.\n');
fprintf(fid, '// |H(f)| of the quantised %d-tap filter, for tb_fir_lpf checks\n', Taps);
fprintf(fid, 'localparam real FIR_GAIN_1K0  = %.6f;\n', gains(1));
fprintf(fid, 'localparam real FIR_GAIN_2K5  = %.6f;\n', gains(2));
fprintf(fid, 'localparam real FIR_GAIN_4K0  = %.6f;\n', gains(3));
fprintf(fid, 'localparam real FIR_GAIN_12K0 = %.6f;\n', gains(4));
fclose(fid);
fprintf('wrote         : %s\n', specFile);

%% ---- response csv + plot -----------------------------------------------
csvFile = fullfile(FirDir, 'fir_response.csv');
fid = fopen(csvFile, 'w');
fprintf(fid, 'freq_Hz,mag_dB,phase_rad\n');
step = max(1, floor(numel(f)/4000));
for k = 1:step:numel(f)
    fprintf(fid, '%.1f,%.4f,%.6f\n', f(k), magdB(k), angle(Hq(k)));
end
fclose(fid);
fprintf('wrote         : %s\n', csvFile);

try
    fig = figure('Visible','off','Position',[100 100 1000 700]);
    subplot(2,1,1);
    plot(f/1e3, magdB, 'LineWidth', 1.2); grid on; hold on;
    yl = ylim;
    plot([Fpass Fpass]/1e3, yl, '--r');
    plot([Fstop Fstop]/1e3, yl, '--m');
    xlim([0 8]); ylim([-80 5]);
    xlabel('frequency [kHz]'); ylabel('|H| [dB]');
    title(sprintf('AMC1306 LPF, %d taps @ Fs = %.1f kHz (pass 1 kHz, stop 2.5 kHz)', ...
                  Taps, Fs/1e3));
    legend('|H(f)|', 'pass edge', 'stop edge', 'Location', 'southwest');
    subplot(2,1,2);
    stem(0:Taps-1, hq, 'filled'); grid on;
    xlabel('tap index'); ylabel('coefficient [LSB]');
    title(sprintf('quantised coefficients (%d-bit, sum %d)', CoefW, sum(hq)));
    exportgraphics(fig, fullfile(FirDir, 'fir_response.png'), 'Resolution', 150);
    close(fig);
    fprintf('wrote         : %s\n', fullfile(FirDir, 'fir_response.png'));
catch ME
    fprintf('plot skipped  : %s\n', ME.message);
end

%% ---- honesty check ------------------------------------------------------
dw   = 2*pi*(Fstop - Fpass)/Fs;          % transition width, rad/sample
N50  = ceil((50 - 8) / (2.285 * dw));    % Kaiser order estimate for 50 dB
if attn < 40
    fprintf('\n*** NOTE: %.1f dB stop band with %d taps at Fs = %.1f kHz.\n', ...
            attn, Taps, Fs/1e3);
    fprintf('*** The 1 -> 2.5 kHz transition is only %.2f %% of Fs; a Kaiser\n', ...
            100*(Fstop-Fpass)/Fs);
    fprintf('*** estimate says ~%d taps are needed for 50 dB.\n', N50);
    fprintf('*** Raise Order (try %d) or decimate before filtering\n', N50+1);
    fprintf('*** (e.g. /4 -> Fs = 15.625 kHz, then 51 taps give ~78 dB).\n');
end
